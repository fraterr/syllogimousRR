export const STRINGS = { en, de, fr, it, es, ru };

let current = 'en';
export const setLang = (lang) => { current = STRINGS[lang] ? lang : 'en'; };
export const getLang = () => current;

/** Translate a key with {placeholders}. Falls back to English, then to the key. */
export function t(key, vars = {}) {
    let s = STRINGS[current][key];
    if (s === undefined) s = en[key];
    if (s === undefined) return key;
    if (Array.isArray(s)) return s;
    return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : `{${k}}`));
}
